/// What to search for, where the listed name alone finds the wrong thing (a state, a country).
pub fn query_for(name: &str) -> &str {
    match name {
        "Washington" => "Washington, D.C.",
        "Luxembourg" => "Luxembourg City",
        "New York" => "New York City",
        "Penang" => "George Town",
        "Kyiv" => "Kyiv",
        n => n,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_city_has_a_known_tier_and_a_country_code() {
        for (tier, name, country) in CITIES {
            assert!(TIERS.contains(tier), "{name}: tier {tier}");
            assert_eq!(country.len(), 2, "{name}: {country}");
            assert!(country.chars().all(|c| c.is_ascii_uppercase()), "{name}: {country}");
        }
        let mut names: Vec<_> = CITIES.iter().map(|c| (c.1, c.2)).collect();
        names.sort();
        names.dedup();
        assert_eq!(names.len(), CITIES.len(), "a city is listed twice");
    }

    #[test]
    fn tiers_come_in_order() {
        let at = |t: &str| TIERS.iter().position(|x| *x == t).unwrap();
        assert!(CITIES.windows(2).all(|w| at(w[0].0) <= at(w[1].0)));
    }
}
